OUT = ROOT / "trade_studies"
DISCL = ("> TSR-1 is an independent conceptual engineering study by Todaro Corp. References to NASA, ESA and other "
         "organizations are used solely as technical and architectural context.\n")


def J(n):
    return json.loads((RES / n).read_text())


def f(x, d=1):
    try:
        if isinstance(x, str):
            return x
        if x is None or (isinstance(x, float) and math.isnan(x)):
            return "—"
        return f"{x:.{d}f}"
    except Exception:
        return str(x)


def table(rows, cols, fmt=None):
    fmt = fmt or {}
    h = "| " + " | ".join(c[1] for c in cols) + " |\n|" + "---|" * len(cols) + "\n"
    for r in rows:
        h += "| " + " | ".join(fmt.get(c[0], lambda v: f(v) if isinstance(v, float) else str(v))(r[c[0]]) for c in cols) + " |\n"
    return h


def write(name, title, body):
    (OUT / name).write_text(f"# {title}\n\n{DISCL}\nGenerated by `trade_studies/build_trade_docs.py` from "
                            f"`simulations/results/`. Method: see `trade_studies/README.md`.\n\n{body}")
    print("wrote", name)


