"""Generate trade-study documents (directive §37) from simulations/results/*.json.

    PYTHONPATH=src python trade_studies/build_trade_docs.py

Decision method used in every trade (no arbitrary scoring):
  1. Screen candidates against hard requirements (pass/fail).
  2. Compare compliant candidates on quantified discriminators computed by the project models.
  3. Select the minimum-delivered-mass compliant candidate unless a discriminator with a quantified
     mission effect (value model, reliability, closure) justifies the mass difference; the
     justification is stated explicitly.
Weighted scoring appears only in TS-03, where weights are the expected work-content fractions of a
DRM-derived task catalogue (not preferences).
"""
from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
